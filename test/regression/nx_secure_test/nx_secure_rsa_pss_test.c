/* Apply the public key to an OpenSSL signature to recover the encoded message. */
static VOID recover_em(const UCHAR *modulus, const UCHAR *signature, UCHAR *em)
{
UINT status;

    status = test_crypto_method_rsa.nx_crypto_init(&test_crypto_method_rsa,
                                                   (UCHAR *)modulus,
                                                   RSA_2048_MODULUS_SIZE << 3,
                                                   NX_CRYPTO_NULL,
                                                   &rsa_ctx, sizeof(rsa_ctx));
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    status = test_crypto_method_rsa.nx_crypto_operation(NX_CRYPTO_ENCRYPT, NX_CRYPTO_NULL,
                                                        &test_crypto_method_rsa,
                                                        (UCHAR *)pss_public_exponent,
                                                        sizeof(pss_public_exponent) << 3,
                                                        (UCHAR *)signature,
                                                        RSA_2048_MODULUS_SIZE,
                                                        NX_CRYPTO_NULL,
                                                        (UCHAR *)rsa_output,
                                                        sizeof(rsa_output),
                                                        &rsa_ctx, sizeof(rsa_ctx),
                                                        NX_CRYPTO_NULL, NX_CRYPTO_NULL);
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    memcpy(em, (UCHAR *)rsa_output, RSA_2048_MODULUS_SIZE);
}

/* Sign, then check the result byte for byte against the reference encoder using
   the salt the signer chose, and check that verification accepts it. */
static VOID check_sign_round_trip(const NX_CRYPTO_METHOD *method, UINT hash_length,
                                  const UCHAR *message_hash, UINT em_bits)
{
UINT  status;
UINT  em_len = (em_bits + 7u) >> 3;
UINT  i;
UCHAR tampered_hash[64];

    /* Fill the whole buffer, so anything written past emLen shows up below. */
    memset(em_buffer, 0xA5, sizeof(em_buffer));
    status = _nx_crypto_rsa_pss_sign(message_hash, hash_length,
                                     em_buffer, (UINT)sizeof(em_buffer), em_bits,
                                     method, pss_metadata, sizeof(pss_metadata),
                                     scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    /* Exactly emLen bytes, not one more. */
    for (i = em_len; i < (UINT)sizeof(em_buffer); i++)
    {
        EXPECT_EQ(0xA5, em_buffer[i]);
    }

    /* Byte-exact against an independent encoder fed the same salt. */
    ref_recover_salt(method, em_buffer, hash_length, hash_length, em_bits, recovered_salt);
    ref_pss_encode(method, message_hash, hash_length, recovered_salt, hash_length,
                   em_bits, ref_em);
    EXPECT_EQ(0, memcmp(em_buffer, ref_em, em_len));

    /* The trailer and the unused leading bits are part of the contract. */
    EXPECT_EQ(0xBC, em_buffer[em_len - 1u]);
    if (8u * em_len != em_bits)
    {
        EXPECT_EQ(0, em_buffer[0] & (UCHAR)(0xFFu << (8u - (8u * em_len - em_bits))));
    }

    status = _nx_crypto_rsa_pss_verify(message_hash, hash_length, em_buffer, em_bits,
                                       method, pss_metadata, sizeof(pss_metadata),
                                       scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    /* A different message must not verify against this encoding. */
    memcpy(tampered_hash, message_hash, hash_length);
    tampered_hash[0] = (UCHAR)(tampered_hash[0] ^ 0x01u);
    status = _nx_crypto_rsa_pss_verify(tampered_hash, hash_length, em_buffer, em_bits,
                                       method, pss_metadata, sizeof(pss_metadata),
                                       scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_NOT_SUCCESSFUL, status);
}

/* Flip one bit of a valid encoding and require rejection. */
static VOID check_tampered_em(const NX_CRYPTO_METHOD *method, UINT hash_length,
                              const UCHAR *message_hash, const UCHAR *valid_em,
                              UINT em_bits, UINT offset, UCHAR xor_mask)
{
UINT  status;
UINT  em_len = (em_bits + 7u) >> 3;

    memcpy(em_buffer, valid_em, em_len);
    em_buffer[offset] = (UCHAR)(em_buffer[offset] ^ xor_mask);

    status = _nx_crypto_rsa_pss_verify(message_hash, hash_length, em_buffer, em_bits,
                                       method, pss_metadata, sizeof(pss_metadata),
                                       scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_NOT_SUCCESSFUL, status);
}

