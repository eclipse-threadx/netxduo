    EXPECT_EQ(0, memcmp(ref_em, pss_sha512_em, RSA_2048_MODULUS_SIZE));

    /* ---- 2. Boundary encodings: emLen == hLen + sLen + 2, PS empty. ---- */

    status = _nx_crypto_rsa_pss_verify(pss_boundary_mhash, sizeof(pss_boundary_mhash),
                                       pss_boundary_em_1039, BOUNDARY_EM_BITS_PARTIAL,
                                       &crypto_method_sha512,
                                       pss_metadata, sizeof(pss_metadata),
                                       scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    status = _nx_crypto_rsa_pss_verify(pss_boundary_mhash, sizeof(pss_boundary_mhash),
                                       pss_boundary_em_1040, BOUNDARY_EM_BITS_EXACT,
                                       &crypto_method_sha512,
                                       pss_metadata, sizeof(pss_metadata),
                                       scratch, sizeof(scratch));
    EXPECT_EQ(NX_CRYPTO_SUCCESS, status);

    /* Pin the reference encoder at these emBits too. The OpenSSL vectors above
       only cover emBits 2047, where one leading bit is unused and PS is long;
       these two add the empty-PS case with and without unused leading bits. */
    ref_pss_encode(&crypto_method_sha512, pss_boundary_mhash, sizeof(pss_boundary_mhash),
                   pss_boundary_salt, sizeof(pss_boundary_salt),
                   BOUNDARY_EM_BITS_PARTIAL, ref_em);
    EXPECT_EQ(0, memcmp(ref_em, pss_boundary_em_1039, BOUNDARY_EM_LEN));

    ref_pss_encode(&crypto_method_sha512, pss_boundary_mhash, sizeof(pss_boundary_mhash),
                   pss_boundary_salt, sizeof(pss_boundary_salt),
                   BOUNDARY_EM_BITS_EXACT, ref_em);
    EXPECT_EQ(0, memcmp(ref_em, pss_boundary_em_1040, BOUNDARY_EM_LEN));

    /* ---- 3. Signing: byte-exact encoding, then a sign/verify round trip. ---- */

    check_sign_round_trip(&crypto_method_sha256, 32, pss_sha256_mhash, RSA_2048_EM_BITS);
