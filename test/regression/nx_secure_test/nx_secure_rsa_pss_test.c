/* Regression test for the RSASSA-PSS primitives in nx_crypto_rsa.c:
   _nx_crypto_rsa_pss_sign(), _nx_crypto_rsa_pss_verify() and the MGF1 helper
   they share. These implement EMSA-PSS-ENCODE and EMSA-PSS-VERIFY from
   RFC 8017 section 9.1, with the salt length pinned to the hash length as
   RFC 8446 section 4.2.3 requires for TLS 1.3.

   The signing side generates its salt internally, so its output is not
   reproducible and cannot be compared against a stored vector directly. This
   test gets byte-exactness anyway by recovering the salt from the encoded
   message the function produced and re-encoding with an independent
   EMSA-PSS-ENCODE written here from the RFC (ref_pss_encode below). That
   reference encoder is not taken on trust: it has to reproduce, byte for byte,
   encoded messages recovered from real OpenSSL signatures before it is used to
   judge anything.

   Vector provenance:
     - pss_sha256_* and pss_sha512_* are RSASSA-PSS signatures produced by
       OpenSSL 3.3.2 over freshly generated RSA-2048 keys, with the encoded
       message recovered by applying the public key to the signature. They are
       known-answer tests for the verification path.
     - pss_boundary_* cover emLen == hLen + sLen + 2, where PS is empty. No
       OpenSSL key of the required size is involved; these come from the same
       RFC 8017 encoder, cross-checked against the OpenSSL vectors above.

   One branch stays uncovered: the failure return after NX_CRYPTO_RBG() in
   _nx_crypto_rsa_pss_sign(). NX_CRYPTO_RBG is a macro resolved at compile
   time, so a test cannot substitute a generator that fails; reaching it needs
   a build configuration that overrides the macro. Everything else in the three
   functions is exercised, including every crypto-call failure return, which
   section 7 reaches by failing each call the functions make, one at a time. */

