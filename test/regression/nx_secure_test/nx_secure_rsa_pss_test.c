/* MGF1 from RFC 8017 appendix B.2.1. */
static VOID ref_mgf1(const NX_CRYPTO_METHOD *method,
                     const UCHAR *seed, UINT seed_length,
                     UCHAR *mask, UINT mask_length)
{
UINT  hash_len = (UINT)(method -> nx_crypto_ICV_size_in_bits >> 3);
UINT  counter = 0;
UINT  offset = 0;
UINT  copy_len;
UCHAR counter_bytes[4];
UCHAR block[64];

    while (offset < mask_length)
    {
        counter_bytes[0] = (UCHAR)((counter >> 24) & 0xFFu);
        counter_bytes[1] = (UCHAR)((counter >> 16) & 0xFFu);
        counter_bytes[2] = (UCHAR)((counter >>  8) & 0xFFu);
        counter_bytes[3] = (UCHAR)( counter        & 0xFFu);

        EXPECT_EQ(NX_CRYPTO_SUCCESS, ref_hash(method, seed, seed_length,
                                              counter_bytes, 4, NX_CRYPTO_NULL, 0, block));

        copy_len = mask_length - offset;
        if (copy_len > hash_len)
        {
            copy_len = hash_len;
        }
        memcpy(&mask[offset], block, copy_len);
        offset += copy_len;
        counter++;
    }
}

/* EMSA-PSS-ENCODE from RFC 8017 section 9.1.1, with the salt supplied. */
static VOID ref_pss_encode(const NX_CRYPTO_METHOD *method,
                           const UCHAR *message_hash, UINT hash_length,
                           const UCHAR *salt, UINT salt_length,
                           UINT em_bits, UCHAR *em)
{
UINT  em_len = (em_bits + 7u) >> 3;
UINT  db_len = em_len - hash_length - 1u;
UINT  i;
UCHAR zero_bits;
UCHAR h[64];
UCHAR db[RSA_2048_MODULUS_SIZE];
UCHAR mask[RSA_2048_MODULUS_SIZE];

    EXPECT_EQ(NX_CRYPTO_SUCCESS, ref_hash(method, pss_zero8, 8, message_hash, hash_length,
                                          salt, salt_length, h));

    memset(db, 0, db_len);
    db[db_len - salt_length - 1u] = 0x01u;
    memcpy(&db[db_len - salt_length], salt, salt_length);

    ref_mgf1(method, h, hash_length, mask, db_len);

    for (i = 0; i < db_len; i++)
    {
        em[i] = (UCHAR)(db[i] ^ mask[i]);
    }

    zero_bits = (UCHAR)(8u * em_len - em_bits);
    if (zero_bits)
    {
        em[0] &= (UCHAR)(0xFFu >> zero_bits);
    }

    memcpy(&em[db_len], h, hash_length);
    em[em_len - 1u] = 0xBCu;
}

/* Undo the DB masking of an encoded message and hand back the salt it carries. */
static VOID ref_recover_salt(const NX_CRYPTO_METHOD *method, const UCHAR *em,
                             UINT hash_length, UINT salt_length, UINT em_bits,
                             UCHAR *salt)
{
UINT  em_len = (em_bits + 7u) >> 3;
UINT  db_len = em_len - hash_length - 1u;
UINT  i;
UCHAR zero_bits;
UCHAR db[RSA_2048_MODULUS_SIZE];
UCHAR mask[RSA_2048_MODULUS_SIZE];

    ref_mgf1(method, &em[db_len], hash_length, mask, db_len);

    for (i = 0; i < db_len; i++)
    {
        db[i] = (UCHAR)(em[i] ^ mask[i]);
    }

    zero_bits = (UCHAR)(8u * em_len - em_bits);
    if (zero_bits)
    {
        db[0] &= (UCHAR)(0xFFu >> zero_bits);
    }

    /* PS must be all zeros and the separator must be present, otherwise the
       encoding the signer produced is malformed and nothing below is meaningful. */
    for (i = 0; i < db_len - salt_length - 1u; i++)
    {
        EXPECT_EQ(0x00, db[i]);
    }
    EXPECT_EQ(0x01, db[db_len - salt_length - 1u]);

    memcpy(salt, &db[db_len - salt_length], salt_length);
}

