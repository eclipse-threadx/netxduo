/* Regression test for TLS 1.3 client authentication with an RSA certificate.

   RFC 8446 section 4.4.3 forbids RSASSA-PKCS1-v1_5 in CertificateVerify, so a
   client holding an RSA certificate has to sign with RSASSA-PSS. This test
   covers the two functions that make that work:

     _nx_secure_tls_process_certificate_request() has to answer a TLS 1.3
     CertificateRequest by selecting rsa_pss_rsae_sha256 for an RSA local
     certificate -- and only when the server actually offered it.

     _nx_secure_tls_send_certificate_verify() has to emit the SignatureScheme
     on the wire and sign the RFC 8446 section 4.4.3 content with PSS.

   The signature is not inspected structurally: the test applies the
   certificate's own public key to it and runs the result through
   _nx_crypto_rsa_pss_verify() against the content the client was supposed to
   sign, which is what a peer does. All three rsae schemes are exercised.

   The two sides are driven directly rather than over a socket. A NetX Duo
   server never offers rsa_pss_rsae_sha256 in its own CertificateRequest --
   nx_secure_tls_send_certificate_request.c derives the list from the
   configured ECC curves -- so a NetX-to-NetX handshake cannot reach this path,
   and a full handshake test would need the server side extended first. */

